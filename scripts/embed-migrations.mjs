// Fold drizzle/*.sql (in journal order) into lib/db/migrations.generated.ts, so
// the migrations ship inside the server bundle and run at runtime
// (lib/db/client.ts) with no file-system reads on the serverless host.
//   node scripts/embed-migrations.mjs
import { readFileSync, writeFileSync } from "node:fs";

const journal = JSON.parse(readFileSync(new URL("../drizzle/meta/_journal.json", import.meta.url), "utf8"));
const out = journal.entries.map((e) => ({
  id: e.tag,
  statements: readFileSync(new URL(`../drizzle/${e.tag}.sql`, import.meta.url), "utf8")
    .split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean),
}));
writeFileSync(new URL("../lib/db/migrations.generated.ts", import.meta.url),
  `// GENERATED by scripts/embed-migrations.mjs from drizzle/*.sql. Do not edit by hand.\n` +
  `export const MIGRATIONS: { id: string; statements: string[] }[] = ${JSON.stringify(out, null, 1)};\n`);
console.log(`Embedded ${out.length} migrations.`);
